-- ============================================================================
-- 社交媒体舆情分析系统 - 高级性能优化索引脚本
-- ============================================================================
-- 脚本说明: 创建高级索引以进一步优化复杂查询性能
-- 创建时间: 2025年
-- 备注: Phase 14 性能优化
-- ============================================================================

-- ============================================================================
-- 1. 热点话题查询专用索引
-- ============================================================================
-- 用于优化：热度 = 帖子数 × 0.7 + 评论数 × 0.3 的计算

CREATE INDEX idx_posts_time_range ON posts(created_at, user_id, post_id);

CREATE INDEX idx_posts_user_time ON posts(user_id, created_at, post_id);

-- ============================================================================
-- 2. 舆情趋势分析专用索引
-- ============================================================================
-- 用于优化：按日期和情感分类的统计查询

CREATE INDEX idx_post_sentiments_date_range ON post_sentiments(post_id, analyzed_at, sentiment);

CREATE INDEX idx_post_sentiments_date_sentiment ON post_sentiments(analyzed_at, sentiment, post_id);

-- ============================================================================
-- 3. 关键词预警系统专用索引
-- ============================================================================
-- 用于优化：最近24小时/7天预警查询

CREATE INDEX idx_alerts_time_keyword ON alerts(created_at, keyword_id, alert_id);

CREATE INDEX idx_alerts_content_time ON alerts(content_type, created_at, alert_id);


-- ============================================================================
-- 4. 分页查询优化索引
-- ============================================================================
-- 用于优化：大量数据的分页查询性能

CREATE INDEX idx_posts_pagination ON posts(created_at DESC, post_id);

CREATE INDEX idx_comments_pagination ON comments(created_at DESC, comment_id);

CREATE INDEX idx_alerts_pagination ON alerts(created_at DESC, alert_id);

-- ============================================================================
-- 5. 管理员操作专用索引
-- ============================================================================
-- 用于优化：管理员用户管理和关键词管理查询

CREATE INDEX idx_users_status_role ON users(status, role, user_id);

CREATE INDEX idx_keywords_category_time ON keywords(category, created_at, keyword_id);

-- ============================================================================
-- 6. 统计分析专用索引
-- ============================================================================
-- 用于优化：各类统计和报表查询

CREATE INDEX idx_users_activity ON users(created_at, user_id);

CREATE INDEX idx_posts_activity ON posts(created_at, post_id);

CREATE INDEX idx_comments_activity ON comments(created_at, post_id, comment_id);

-- ============================================================================
-- 7. 数据清理和归档优化索引
-- ============================================================================
-- 用于优化：批量删除和归档操作

CREATE INDEX idx_posts_cleanup ON posts(created_at, post_id);

CREATE INDEX idx_alerts_cleanup ON alerts(created_at, alert_id);

-- ============================================================================
-- 高级索引创建完成
-- ============================================================================
-- 索引说明：
-- 1. 这些索引专门为复杂查询和统计分析场景设计
-- 2. 优先考虑常用查询路径，避免过度索引
-- 3. 复合索引顺序很重要，遵循最左前缀原则
-- 4. 定期监控索引使用情况，删除未使用的索引
-- 5. 在高并发写入场景下，索引会增加写入开销
--
-- 性能测试建议：
-- - 热点话题查询：验证在100万条帖子数据下的查询时间
-- - 舆情趋势分析：验证30天数据聚合查询时间
-- - 分页查询：验证100页以后的查询性能
-- - 预警查询：验证24小时内预警数据的查询性能
-- ============================================================================
